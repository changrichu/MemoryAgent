ROUTER_PROMPT = """你是一个对话系统的智能路由器,需要判断用户问题是否需要调用外部知识/记忆检索。

【用户最近的对话上下文】
{history}

【可选决策】
- "direct":不需要检索,可以直接回答(闲聊、问候、创作、情感支持)
- "retrieve_short":需要短期记忆(L1+L2),例如"刚才/最近/上次说过的"
- "retrieve_long":需要长期记忆或私域知识(L3),例如"我之前提到过的咖啡"、具体业务问题
- "retrieve_all":复杂多跳问题,可能需要全部记忆层 + 多次检索

【决策辅助判断】
- 含时间指代词("上次"、"之前"、"记得"):→ retrieve_short
- 含实体(具体名词、品牌、产品):→ retrieve_long
- 询问事实/数字/规则:→ retrieve_long
- 闲聊/创作/情感:→ direct
- 复杂组合问题:→ retrieve_all

【严格输出 JSON】(不要任何其他内容):
{{"decision": "direct|retrieve_short|retrieve_long|retrieve_all", "reason": "你的判断理由", "sub_questions": ["如果是复杂问题,拆解成子问题"]}}
"""


